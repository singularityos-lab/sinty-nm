package nmapi

import (
	"os"
	"path/filepath"
	"reflect"
	"testing"

	"github.com/singularityos-lab/sinty-nm/internal/core"
)

func withResolver(t *testing.T, resolv string, records map[string]string) {
	t.Helper()
	dir := t.TempDir()
	recs := filepath.Join(dir, "interfaces")
	if err := os.Mkdir(recs, 0o755); err != nil {
		t.Fatal(err)
	}
	for name, body := range records {
		if err := os.WriteFile(filepath.Join(recs, name), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	path := filepath.Join(dir, "resolv.conf")
	if err := os.WriteFile(path, []byte(resolv), 0o644); err != nil {
		t.Fatal(err)
	}
	oldResolv, oldDir := resolvConf, resolvconfDir
	resolvConf, resolvconfDir = path, recs
	t.Cleanup(func() { resolvConf, resolvconfDir = oldResolv, oldDir })
}

func TestAdoptedResolverReadsTheInterfaceRecords(t *testing.T) {
	withResolver(t, core.ResolvConfMarker+"\nnameserver 10.0.0.1\n", map[string]string{
		"wlan0.dns":    "nameserver 192.168.1.1\n",
		"wlan0.domain": "search homenet\n",
		"wlan01.dns":   "nameserver 10.9.9.9\n",
		"eth0.dhcp":    "nameserver 172.16.0.1\n",
	})
	dns, domains := adoptedResolver("wlan0")
	if len(dns) != 1 || dns[0].String() != "192.168.1.1" {
		t.Fatalf("dns %v", dns)
	}
	if !reflect.DeepEqual(domains, []string{"homenet"}) {
		t.Fatalf("domains %v", domains)
	}
}

func TestAdoptedResolverIgnoresItsOwnResolvConf(t *testing.T) {
	withResolver(t, core.ResolvConfMarker+"\nnameserver 10.0.0.1\nsearch stale\n", nil)
	dns, domains := adoptedResolver("wlan0")
	if len(dns) != 0 || len(domains) != 0 {
		t.Fatalf("learned from its own file: %v %v", dns, domains)
	}
}

func TestAdoptedResolverFallsBackToAForeignResolvConf(t *testing.T) {
	withResolver(t, "# Generated by resolvconf\nnameserver 192.168.1.1\nsearch lan\n", nil)
	dns, domains := adoptedResolver("wlan0")
	if len(dns) != 1 || dns[0].String() != "192.168.1.1" || !reflect.DeepEqual(domains, []string{"lan"}) {
		t.Fatalf("dns %v domains %v", dns, domains)
	}
}
